// Small res/ folders, many of which aapt2 rejects: hydroid must reject the same, for the same
// reason, and dump the others the same.
TEST(Aapt2Table, CasesLikeAapt2) {
  const nlohmann::json golden = nlohmann::json::parse(readFile(HYDROID_AAPT2_TABLE_CASES));
  const std::string package = golden.at("package").get<std::string>();
  std::set<std::string, std::less<>> rejected;
  // The cases whose error from aapt2 runs on to more lines.
  std::set<std::string, std::less<>> longer;
  ASSERT_GT(golden.at("cases").size(), 150u);
  for (const nlohmann::json& c : golden.at("cases")) {
    const std::string name = c.at("name").get<std::string>();
    SCOPED_TRACE(name);
    TempDir dir;
    for (const auto& [path, content] : c.at("files").items()) {
      dir.write("res/" + path, content.get<std::string>());
    }
    std::filesystem::create_directories(dir.path() / "res");
    ResourceTable table;
    std::vector<Diagnostic> errors;
    const bool loaded = table.addPackage(dir.path() / "res", package, kAppPackageId, &errors);
    if (c.at("aapt2").is_null()) {
      rejected.insert(name);
      if (c.at("error").get<std::string>().find('\n') != std::string::npos) longer.insert(name);
      std::string path;
      const std::string aapt2 = likeHydroid(c.at("error").get<std::string>(), package, &path);
      if (loaded) {
        ADD_FAILURE() << "aapt2 rejects it (" << aapt2 << "), hydroid takes it:\n" << dumpOf(table);
        continue;
      }
      if (errors.empty()) {
        ADD_FAILURE() << "aapt2 rejects it (" << aapt2 << "), hydroid with no error";
        continue;
      }
      // The first errors of the two, as the later ones may come of the first.
      const std::string& first = errors.front().message;
      if (!path.empty()) {
        const std::string file = errors.front().file.generic_string();
        EXPECT_TRUE(file.size() >= path.size() &&
                    file.compare(file.size() - path.size(), path.size(), path) == 0)
            << "aapt2 names " << path << ", hydroid " << file;
      }
      const auto other = kOtherWords.find(name);
      if (other == kOtherWords.end()) {
        EXPECT_NE(first.find(aapt2), std::string::npos)
            << "aapt2 rejects it: " << aapt2 << "\nhydroid:" << errorsOf(errors);
        continue;
      }
      EXPECT_EQ(aapt2, other->second.aapt2) << "aapt2's error is not the one kOtherWords has";
      if (first.find(aapt2) != std::string::npos) {
        ADD_FAILURE() << "hydroid says what aapt2 says now, " << aapt2
                      << "; take the case out of kOtherWords";
      } else {
        EXPECT_EQ(first, other->second.hydroid) << "aapt2 rejects it: " << aapt2;
      }
      continue;
    }
    if (!loaded) {
      ADD_FAILURE() << "aapt2 takes it, hydroid rejects it:" << errorsOf(errors);
      continue;
    }
    const std::string difference = firstDifference(c.at("aapt2").get<std::string>(), dumpOf(table));
    EXPECT_TRUE(difference.empty()) << difference;
  }
  EXPECT_GT(rejected.size(), 50u);
  // aapt2 prints the string these errors are about on the line after, which gen_aapt2_table.py
  // keeps, so that hydroid's words are compared to the string too (#152).
  for (const char* name : {"string-apostrophe", "string-bad-unicode", "string-array-apostrophe",
                           "style-string-attr", "plurals-apostrophe"}) {
    EXPECT_TRUE(longer.count(name)) << name << ": aapt2's error has no line after its first";
  }
  for (const auto& [name, words] : kOtherWords) {
    EXPECT_TRUE(rejected.count(name)) << "kOtherWords has " << name << ", not a case aapt2 rejects";
  }
}

// gen_aapt2_strings.py's element for row `i`.
std::string stringElement(size_t i, const std::string& tag, const std::string& text) {
  const std::string name = "s" + std::to_string(i);
  if (tag == "string") return "<string name=\"" + name + "\">" + text + "</string>";
  if (tag == "item") return "<item type=\"string\" name=\"" + name + "\">" + text + "</item>";
  return "<style name=\"" + name + "\"><item name=\"str\">" + text + "</item></style>";
}

// Thousands of strings, as a <string>, an <item type="string"> and a style item of a string
// attribute: whitespace, quotes, escapes, tags, references and format arguments. The ones aapt2
// takes load together and must print the same; each it rejects must fail on its own, with a first
// error that says what aapt2's does of it on its own.
TEST(Aapt2Table, StringsLikeAapt2) {
  const nlohmann::json golden = nlohmann::json::parse(readFile(HYDROID_AAPT2_STRINGS));
  const std::string package = golden.at("package").get<std::string>();
  const std::string head =
      "<resources xmlns:xliff=\"urn:oasis:names:tc:xliff:document:1.2\" "
      "xmlns:other=\"urn:example:other\">\n" +
      golden.at("prelude").get<std::string>();
  const nlohmann::json& rows = golden.at("rows");
  ASSERT_GT(rows.size(), 3000u);

  std::string accepted = head;
  size_t rejected = 0;
  for (size_t i = 0; i < rows.size(); i++) {
    if (rows[i].at(2).is_null()) {
      rejected++;
      continue;
    }
    accepted += stringElement(i, rows[i].at(0), rows[i].at(1)) + "\n";
  }
  TempDir dir;
  dir.write("res/values/strings.xml", accepted + "</resources>\n");
  ResourceTable table;
  std::vector<Diagnostic> errors;
  ASSERT_TRUE(table.addPackage(dir.path() / "res", package, kAppPackageId, &errors))
      << errorsOf(errors);
  const Package& p = *table.package(package);

  for (size_t i = 0; i < rows.size(); i++) {
    const std::string tag = rows[i].at(0);
    const std::string text = rows[i].at(1);
    SCOPED_TRACE(tag + " " + testing::PrintToString(text));
    if (rows[i].at(2).is_null()) {
      TempDir one;
      one.write("res/values/strings.xml", head + stringElement(i, tag, text) + "\n</resources>\n");
      ResourceTable alone;
      std::vector<Diagnostic> aloneErrors;
      std::string path;
      const std::string aapt2 = likeHydroid(rows[i].at(3).get<std::string>(), package, &path);
      if (alone.addPackage(one.path() / "res", package, kAppPackageId, &aloneErrors)) {
        ADD_FAILURE() << "aapt2 rejects it (" << aapt2 << "), hydroid takes it";
        continue;
      }
      if (aloneErrors.empty()) {
        ADD_FAILURE() << "aapt2 rejects it (" << aapt2 << "), hydroid with no error";
        continue;
      }
      // As in CasesLikeAapt2, but with no list of other words: hydroid's first error takes in
      // aapt2's for every string.
      const std::string& first = aloneErrors.front().message;
      EXPECT_NE(first.find(aapt2), std::string::npos)
          << "aapt2 rejects it: " << aapt2 << "\nhydroid:" << errorsOf(aloneErrors);
      continue;
    }
    const ResType type = tag == "style" ? ResType::Style : ResType::String;
    const std::optional<ResId> id = table.find(package, type, "s" + std::to_string(i));
    ASSERT_TRUE(id);
    EXPECT_EQ(describe(p, type, table.entry(*id)->candidates.at(0).value),
              rows[i].at(2).get<std::string>());
  }
  EXPECT_GT(rejected, 300u);
}

