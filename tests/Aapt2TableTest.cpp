std::string readFile(const char* path) {
  std::ifstream in(path, std::ios::binary);
  EXPECT_TRUE(in) << "cannot open " << path;
  std::stringstream s;
  s << in.rdbuf();
  return s.str();
}

// A golden dump without its first line, which says what made it.
std::string goldenDump(const char* path) {
  std::string text = readFile(path);
  const size_t newline = text.find('\n');
  EXPECT_TRUE(text.rfind("# Generated by", 0) == 0) << path << " has no header";
  return newline == std::string::npos ? std::string() : text.substr(newline + 1);
}

std::vector<std::string> lines(const std::string& text) {
  std::vector<std::string> out;
  std::istringstream in(text);
  for (std::string line; std::getline(in, line);) out.push_back(line);
  return out;
}

// The first line where `actual` differs from `expected`, with the lines around it; "" if none.
std::string firstDifference(const std::string& expected, const std::string& actual) {
  if (expected == actual) return {};
  const std::vector<std::string> e = lines(expected);
  const std::vector<std::string> a = lines(actual);
  size_t i = 0;
  while (i < e.size() && i < a.size() && e[i] == a[i]) i++;
  std::ostringstream out;
  out << "first difference at line " << i + 1 << "\n";
  const size_t from = i >= 3 ? i - 3 : 0;
  for (size_t j = from; j < i + 3 && j < e.size(); j++) out << "  aapt2:   " << e[j] << "\n";
  for (size_t j = from; j < i + 3 && j < a.size(); j++) out << "  hydroid: " << a[j] << "\n";
  if (i == e.size() && i == a.size()) out << "  (the same lines, but for the end of the text)\n";
  return out.str();
}

std::string errorsOf(const std::vector<Diagnostic>& errors) {
  std::ostringstream out;
  for (const Diagnostic& d : errors) out << "\n  " << d;
  return out.str();
}

std::string dumpOf(const ResourceTable& table) {
  std::ostringstream out;
  dump(out, table);
  return out.str();
}

void expectDumpsLikeAapt2(const char* res, const char* package, const char* golden) {
  ResourceTable table;
  std::vector<Diagnostic> errors;
  ASSERT_TRUE(table.addPackage(res, package, kAppPackageId, &errors)) << errorsOf(errors);
  const std::string difference = firstDifference(goldenDump(golden), dumpOf(table));
  EXPECT_TRUE(difference.empty()) << res << ": " << difference;
}

