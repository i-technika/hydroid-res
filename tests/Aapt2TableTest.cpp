// Step 4 completion check: hydroid's ResourceTable loads res/ folders as aapt2 compiles and links
// them, as `aapt2 dump resources` shows. golden/aapt2/ holds what aapt2 dumps of them, written by
// scripts/golden/gen_aapt2_table.py and gen_aapt2_strings.py from the SDK's aapt2.

#include <gtest/gtest.h>
#include <nlohmann/json.hpp>

#include <fstream>
#include <sstream>
#include <string>
#include <vector>

#include "TempDir.h"
