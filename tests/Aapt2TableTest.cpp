using test::TempDir;

std::string readFile(const char* path) {
  std::ifstream in(path, std::ios::binary);
  EXPECT_TRUE(in) << "cannot open " << path;
  std::stringstream s;
  s << in.rdbuf();
  return s.str();
}

// A golden dump without its first line, which says what made it.
std::string goldenDump(const char* path) {
  std::string text = readFile(path);
  const size_t newline = text.find('\n');
  EXPECT_TRUE(text.rfind("# Generated by", 0) == 0) << path << " has no header";
  return newline == std::string::npos ? std::string() : text.substr(newline + 1);
}

std::vector<std::string> lines(const std::string& text) {
  std::vector<std::string> out;
  std::istringstream in(text);
  for (std::string line; std::getline(in, line);) out.push_back(line);
  return out;
}

// The first line where `actual` differs from `expected`, with the lines around it; "" if none.
std::string firstDifference(const std::string& expected, const std::string& actual) {
  if (expected == actual) return {};
  const std::vector<std::string> e = lines(expected);
  const std::vector<std::string> a = lines(actual);
  size_t i = 0;
  while (i < e.size() && i < a.size() && e[i] == a[i]) i++;
  std::ostringstream out;
  out << "first difference at line " << i + 1 << "\n";
  const size_t from = i >= 3 ? i - 3 : 0;
  for (size_t j = from; j < i + 3 && j < e.size(); j++) out << "  aapt2:   " << e[j] << "\n";
  for (size_t j = from; j < i + 3 && j < a.size(); j++) out << "  hydroid: " << a[j] << "\n";
  if (i == e.size() && i == a.size()) out << "  (the same lines, but for the end of the text)\n";
  return out.str();
}

std::string errorsOf(const std::vector<Diagnostic>& errors) {
  std::ostringstream out;
  for (const Diagnostic& d : errors) out << "\n  " << d;
  return out.str();
}

std::string dumpOf(const ResourceTable& table) {
  std::ostringstream out;
  dump(out, table);
  return out.str();
}

void expectDumpsLikeAapt2(const char* res, const char* package, const char* golden) {
  ResourceTable table;
  std::vector<Diagnostic> errors;
  ASSERT_TRUE(table.addPackage(res, package, kAppPackageId, &errors)) << errorsOf(errors);
  const std::string difference = firstDifference(goldenDump(golden), dumpOf(table));
  EXPECT_TRUE(difference.empty()) << res << ": " << difference;
}

// Every kind of value and file, configurations in their order, ids, styles and attributes.
TEST(Aapt2Table, GoldenTableDumpsLikeAapt2) {
  expectDumpsLikeAapt2(HYDROID_TABLE_RES_DIR, "com.itechnika.hydroid.table", HYDROID_AAPT2_TABLE);
}

TEST(Aapt2Table, GoldenAppDumpsLikeAapt2) {
  expectDumpsLikeAapt2(HYDROID_TEST_RES_DIR, "com.itechnika.hydroid.golden",
                       HYDROID_AAPT2_APP_TABLE);
}

// Small res/ folders, many of which aapt2 rejects: hydroid must reject the same, and dump the
// others the same.
TEST(Aapt2Table, CasesLikeAapt2) {
  const nlohmann::json golden = nlohmann::json::parse(readFile(HYDROID_AAPT2_TABLE_CASES));
  const std::string package = golden.at("package").get<std::string>();
  int rejected = 0;
  ASSERT_GT(golden.at("cases").size(), 150u);
  for (const nlohmann::json& c : golden.at("cases")) {
    const std::string name = c.at("name").get<std::string>();
    SCOPED_TRACE(name);
    TempDir dir;
    for (const auto& [path, content] : c.at("files").items()) {
      dir.write("res/" + path, content.get<std::string>());
    }
    std::filesystem::create_directories(dir.path() / "res");
    ResourceTable table;
    std::vector<Diagnostic> errors;
    const bool loaded = table.addPackage(dir.path() / "res", package, kAppPackageId, &errors);
    if (c.at("aapt2").is_null()) {
      rejected++;
      EXPECT_FALSE(loaded) << "aapt2 rejects it (" << c.value("error", "")
                           << "), hydroid takes it:\n"
                           << dumpOf(table);
      continue;
    }
    if (!loaded) {
      ADD_FAILURE() << "aapt2 takes it, hydroid rejects it:" << errorsOf(errors);
      continue;
    }
    const std::string difference = firstDifference(c.at("aapt2").get<std::string>(), dumpOf(table));
    EXPECT_TRUE(difference.empty()) << difference;
  }
  EXPECT_GT(rejected, 50);
}

// gen_aapt2_strings.py's element for row `i`.
std::string stringElement(size_t i, const std::string& tag, const std::string& text) {
  const std::string name = "s" + std::to_string(i);
  if (tag == "string") return "<string name=\"" + name + "\">" + text + "</string>";
  if (tag == "item") return "<item type=\"string\" name=\"" + name + "\">" + text + "</item>";
  return "<style name=\"" + name + "\"><item name=\"str\">" + text + "</item></style>";
}

// Thousands of strings, as a <string>, an <item type="string"> and a style item of a string
// attribute: whitespace, quotes, escapes, tags, references and format arguments. The ones aapt2
// takes load together and must print the same; each it rejects must fail on its own.
TEST(Aapt2Table, StringsLikeAapt2) {
  const nlohmann::json golden = nlohmann::json::parse(readFile(HYDROID_AAPT2_STRINGS));
  const std::string package = golden.at("package").get<std::string>();
  const std::string head =
      "<resources xmlns:xliff=\"urn:oasis:names:tc:xliff:document:1.2\" "
      "xmlns:other=\"urn:example:other\">\n" +
      golden.at("prelude").get<std::string>();
  const nlohmann::json& rows = golden.at("rows");
  ASSERT_GT(rows.size(), 3000u);

  std::string accepted = head;
  size_t rejected = 0;
  for (size_t i = 0; i < rows.size(); i++) {
    if (rows[i].at(2).is_null()) {
      rejected++;
      continue;
    }
    accepted += stringElement(i, rows[i].at(0), rows[i].at(1)) + "\n";
  }
  TempDir dir;
  dir.write("res/values/strings.xml", accepted + "</resources>\n");
  ResourceTable table;
  std::vector<Diagnostic> errors;
  ASSERT_TRUE(table.addPackage(dir.path() / "res", package, kAppPackageId, &errors))
      << errorsOf(errors);
  const Package& p = *table.package(package);

  for (size_t i = 0; i < rows.size(); i++) {
    const std::string tag = rows[i].at(0);
    const std::string text = rows[i].at(1);
    SCOPED_TRACE(tag + " " + testing::PrintToString(text));
    if (rows[i].at(2).is_null()) {
      TempDir one;
      one.write("res/values/strings.xml", head + stringElement(i, tag, text) + "\n</resources>\n");
      ResourceTable alone;
      EXPECT_FALSE(alone.addPackage(one.path() / "res", package, kAppPackageId))
          << "aapt2 rejects it, hydroid takes it";
      continue;
    }
    const ResType type = tag == "style" ? ResType::Style : ResType::String;
    const std::optional<ResId> id = table.find(package, type, "s" + std::to_string(i));
    ASSERT_TRUE(id);
    EXPECT_EQ(describe(p, type, table.entry(*id)->candidates.at(0).value),
              rows[i].at(2).get<std::string>());
  }
  EXPECT_GT(rejected, 300u);
}

