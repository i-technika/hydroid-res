// aapt2's error as hydroid's errors put it, with the file it names in `path` ("" if none).
// hydroid's errors leave out the name of `package` where they name a resource of it: "resource
// string/a (aka com.probe:string/a) not found" and "no default product defined for resource
// com.probe:string/a" lose "(aka ...)" and "com.probe:". They leave the file to Diagnostic::file:
// "invalid file path 'res/foo\x.png'" loses " 'res/foo\x.png'", and `path` is "res/foo/x.png".
std::string likeHydroid(std::string error, const std::string& package, std::string* path) {
  path->clear();
  if (const size_t at = error.find(" 'res/"); at != std::string::npos) {
    const size_t end = error.find('\'', at + 2);
    if (end != std::string::npos) {
      *path = error.substr(at + 2, end - at - 2);
      std::replace(path->begin(), path->end(), '\\', '/');
      error.erase(at, end + 1 - at);
    }
  }
  for (size_t at; (at = error.find(" (aka ")) != std::string::npos;) {
    const size_t end = error.find(')', at);
    if (end == std::string::npos) break;
    error.erase(at, end + 1 - at);
  }
  const std::string prefix = package + ":";
  for (size_t at = 0; (at = error.find(prefix, at)) != std::string::npos;) {
    // Not in "attr/com.probe:", the name of an entry.
    if (at == 0 || error[at - 1] == ' ' || error[at - 1] == '\'') {
      error.erase(at, prefix.size());
    } else {
      at += prefix.size();
    }
  }
  return error;
}

// The first error of each, aapt2's as likeHydroid() puts it.
struct OtherWords {
  std::string aapt2;
  std::string hydroid;
};

