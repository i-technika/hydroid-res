def ordered_flats(aapt2: Path, res: Path, out: Path, compiled: set) -> list:
    """The .flat file of each file of `res` that compile --dir made one of (`compiled`, the names
    in its zip), each compiled again on its own into a folder of its own, in the order of the
    folder/name it came from, which link merges them in. aapt2 names each, so that a folder that
    ends in '-' (values-/) or a raw/x.arsc needs no guessing. Paths are relative to `out`."""
    # By folder/name, compared as Python compares strings: by code point, as UTF-8 bytes order.
    sources = sorted(f"{d.name}/{f.name}" for d in res.iterdir()
                     if d.is_dir() and not d.name.startswith(".")
                     for f in d.iterdir() if f.is_file() and not f.name.startswith("."))
    out.mkdir(parents=True, exist_ok=True)  # link runs in it, though res/ has no file to compile
    order = []
    source_of = {}
    for i, rel in enumerate(sources):
        dest = out / str(i)
        dest.mkdir(parents=True)
        if subprocess.run([str(aapt2), "compile", str(res / rel), "-o", str(dest)],
                          capture_output=True).returncode != 0:
            continue
        for flat in dest.iterdir():
            if flat.name not in compiled:
                continue
            if flat.name in source_of:
                sys.exit(f"{rel} and {source_of[flat.name]} of {res} both compile to {flat.name}")
            source_of[flat.name] = rel
            order.append(f"{i}/{flat.name}")
    if set(source_of) != compiled:
        sys.exit(f"compile --dir made {sorted(compiled - set(source_of))} of {res}, "
                 "which no file compiled on its own gives")
    return order


# What a line of aapt2's own starts with: "error: ", or before it the file it is about, and its
# line: an absolute path, as "C:\...\v.xml:1: error: " or "/.../v.xml: warn: ", or the .flat file
# link takes from its folder, as "1/values_b.arsc.flat: error: " (ordered_flats()).
AAPT2_WHERE = r"(?:(?:[A-Za-z]:\\|/|\d+/)[^\n]*?: )?"
AAPT2_LINE = rf"{AAPT2_WHERE}(?:error|warn|note): "
# An error runs to the next such line, as aapt2 prints the string an error is about on the line
# after it, "unescaped apostrophe in string\n\"it's\"", and the newlines of a name it does not
# find: "resource attr/a\nb (aka com.probe:attr/a\nb) not found". So "error: " or "warn: " in the
# string is kept, but a line of it that starts as one of aapt2's ends the error there: no input
# of the scripts has one.
AAPT2_ERROR = re.compile(rf"^({AAPT2_WHERE})error: (.*?)(?=\n{AAPT2_LINE}|\n*\Z)", re.M | re.S)


def aapt2_errors(stderr: str) -> list:
    """(where, error) of each error aapt2 prints, in order: the path and line before "error: ",
    and the error without the period it ends with, and without the temporary folder a file name
    of its first line starts with. The lines after the first are a string or name of the input,
    as it is."""
    errors = []
    for m in AAPT2_ERROR.finditer(stderr.replace("\r", "")):
        first, *rest = m[2].split("\n")
        first = re.sub(r"[^\s']*[\\/]res[\\/]", "res/", first)
        errors.append((m[1], "\n".join([first, *rest]).rstrip(".")))
    return errors


def link_dump(aapt2: Path, jar: Path, res: Path, package: str, work: Path):
    """Compiles and links `res`: (the dump, None), or (None, the first error)."""
    work.mkdir(parents=True, exist_ok=True)
    # A zip, which fails on two files that compile to the same .flat name, as a folder would not.
    archive = work / "c.zip"
    result = subprocess.run([str(aapt2), "compile", "--dir", str(res), "-o", str(archive)],
                            capture_output=True, text=True, encoding="utf-8")
    if result.returncode == 0:
        manifest = work / "AndroidManifest.xml"
        manifest.write_text('<manifest xmlns:android="http://schemas.android.com/apk/res/android" '
                            f'package="{package}"/>\n')
        apk = work / "out.apk"
        with zipfile.ZipFile(archive) as z:
            names = [info.filename for info in z.infolist()]
        flats = work / "flat"
        if len(set(names)) == len(names):
            # Relative to the folder of .flat files, so that a large res/ stays within Windows's
            # limit on the length of a command line.
            order = ordered_flats(aapt2, res, flats, set(names))
        else:
            # Two files that compile to one name, as values-/a.xml and values/a.xml: link takes
            # the zip as it is and fails on it (#122).
            flats.mkdir(parents=True)
            order = [str(archive)]
        result = subprocess.run([str(aapt2), "link", "-I", str(jar), "--manifest", str(manifest),
                                 *LINK_FLAGS, "-o", str(apk), *order],
                                capture_output=True, text=True, encoding="utf-8", cwd=flats)
        if result.returncode == 0:
            dump = subprocess.run([str(aapt2), "dump", "resources", str(apk)], check=True,
                                  capture_output=True, text=True, encoding="utf-8").stdout
            dump = dump.replace("\r", "")
            if not dump.startswith("Binary APK\n"):
                sys.exit(f"unexpected dump of {res}:\n{dump}")
            return dump[len("Binary APK\n"):], None
    errors = aapt2_errors(result.stderr)
    if not errors:
        sys.exit(f"aapt2 failed on {res} with no error:\n{result.stderr}")
    return None, errors[0][1]


def run_case(aapt2: Path, jar: Path, tmp: Path, name: str):
    res = tmp / name / "res"
    for rel, text in CASES[name].items():
        path = res / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    res.mkdir(parents=True, exist_ok=True)
    return link_dump(aapt2, jar, res, CASE_PACKAGE, tmp / name / "out")


def write_dump(path: Path, dump: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# {HEADER}\n")
        out.write(dump)


def main() -> None:
    table_out = out_path(GOLDEN / "table.txt")
    app_out = out_path(GOLDEN / "app_table.txt")
    cases_out = out_path(GOLDEN / "table_cases.json")
    tools, jar = sdk_tools("aapt2")
    aapt2 = tools / f"aapt2{EXE}"

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for res, package, out in [(TABLE_RES, TABLE_PACKAGE, table_out),
                                  (APP_RES, APP_PACKAGE, app_out)]:
            dump, error = link_dump(aapt2, jar, res, package, tmp / out.stem)
            if error:
                sys.exit(f"aapt2 rejects {res.relative_to(ROOT)}: {error}")
            write_dump(out, dump)
            print(f"wrote {out.relative_to(ROOT)}")
        with ThreadPoolExecutor(os.cpu_count()) as pool:
            results = dict(zip(CASES, pool.map(lambda n: run_case(aapt2, jar, tmp, n), CASES)))

    cases_out.parent.mkdir(parents=True, exist_ok=True)
    with open(cases_out, "w", encoding="utf-8", newline="\n") as out:
        # One case a line, so that a change shows as the cases it changes.
        out.write(f'{{"generated": {json.dumps(HEADER)},\n "package": "{CASE_PACKAGE}",\n'
                  ' "cases": [\n')
        rows = []
        for name, files in CASES.items():
            dump, error = results[name]
            row = {"name": name, "files": files, "aapt2": dump}
            if error:
                row["error"] = error
            rows.append("  " + json.dumps(row, ensure_ascii=False))
        out.write(",\n".join(rows) + "\n]}\n")
    rejected = sum(1 for d, _ in results.values() if d is None)
    print(f"wrote {len(CASES)} cases ({rejected} rejected) to {cases_out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
