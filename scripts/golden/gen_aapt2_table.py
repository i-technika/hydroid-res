def link_dump(aapt2: Path, jar: Path, res: Path, package: str, work: Path):
    """Compiles and links `res`: (the dump, None), or (None, the first error)."""
    work.mkdir(parents=True, exist_ok=True)
    flat = work / "c.zip"
    result = subprocess.run([str(aapt2), "compile", "--dir", str(res), "-o", str(flat)],
                            capture_output=True, text=True, encoding="utf-8")
    if result.returncode == 0:
        manifest = work / "AndroidManifest.xml"
        manifest.write_text('<manifest xmlns:android="http://schemas.android.com/apk/res/android" '
                            f'package="{package}"/>\n')
        apk = work / "out.apk"
        result = subprocess.run([str(aapt2), "link", "-I", str(jar), "--manifest", str(manifest),
                                 *LINK_FLAGS, "-o", str(apk), str(flat)],
                                capture_output=True, text=True, encoding="utf-8")
        if result.returncode == 0:
            dump = subprocess.run([str(aapt2), "dump", "resources", str(apk)], check=True,
                                  capture_output=True, text=True, encoding="utf-8").stdout
            dump = dump.replace("\r", "")
            if not dump.startswith("Binary APK\n"):
                sys.exit(f"unexpected dump of {res}:\n{dump}")
            return dump[len("Binary APK\n"):], None
    errors = [m[1] for m in re.finditer(r"error: (.*)", result.stderr.replace("\r", ""))]
    if not errors:
        sys.exit(f"aapt2 failed on {res} with no error:\n{result.stderr}")
    # Without the temporary folder the file names start with.
    return None, re.sub(r"[^\s']*[\\/]res[\\/]", "res/", errors[0]).rstrip(".")


def run_case(aapt2: Path, jar: Path, tmp: Path, name: str):
    res = tmp / name / "res"
    for rel, text in CASES[name].items():
        path = res / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    res.mkdir(parents=True, exist_ok=True)
    return link_dump(aapt2, jar, res, CASE_PACKAGE, tmp / name / "out")


def write_dump(path: Path, dump: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# {HEADER}\n")
        out.write(dump)


def main() -> None:
    table_out = out_path(GOLDEN / "table.txt")
    app_out = out_path(GOLDEN / "app_table.txt")
    cases_out = out_path(GOLDEN / "table_cases.json")
    tools, jar = sdk_tools("aapt2")
    aapt2 = tools / f"aapt2{EXE}"

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for res, package, out in [(TABLE_RES, TABLE_PACKAGE, table_out),
                                  (APP_RES, APP_PACKAGE, app_out)]:
            dump, error = link_dump(aapt2, jar, res, package, tmp / out.stem)
            if error:
                sys.exit(f"aapt2 rejects {res.relative_to(ROOT)}: {error}")
            write_dump(out, dump)
            print(f"wrote {out.relative_to(ROOT)}")
        with ThreadPoolExecutor(os.cpu_count()) as pool:
            results = dict(zip(CASES, pool.map(lambda n: run_case(aapt2, jar, tmp, n), CASES)))

    cases_out.parent.mkdir(parents=True, exist_ok=True)
    with open(cases_out, "w", encoding="utf-8", newline="\n") as out:
        # One case a line, so that a change shows as the cases it changes.
        out.write(f'{{"generated": {json.dumps(HEADER)},\n "package": "{CASE_PACKAGE}",\n'
                  ' "cases": [\n')
        rows = []
        for name, files in CASES.items():
            dump, error = results[name]
            row = {"name": name, "files": files, "aapt2": dump}
            if error:
                row["error"] = error
            rows.append("  " + json.dumps(row, ensure_ascii=False))
        out.write(",\n".join(rows) + "\n]}\n")
    rejected = sum(1 for d, _ in results.values() if d is None)
    print(f"wrote {len(CASES)} cases ({rejected} rejected) to {cases_out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
